"""``docs/CLI.md``: the command reference, generated from the typer command tree.

Nothing here is hand-written per command. The page is a walk of the ``click``
command that typer builds from :data:`studioforge.__main__.app`: every command and
sub-command, its one-paragraph help, its usage line, its arguments and options
with types, defaults and help. Add a command or an option and the page changes on
the next ``scripts/gen_docs.py`` run; ``tests/unit/test_contracts_drift.py`` fails
until it does.

Deterministic on purpose (sorted, no environment-derived values), so it can be
diffed in CI.
"""

from __future__ import annotations

import inspect
from typing import Any, cast

import click
import typer.main

__all__ = ["command_paths", "render_markdown"]


def _root() -> click.Command:
    from studioforge.__main__ import app

    return cast(click.Command, typer.main.get_command(app))


def _walk(command: click.Command, prefix: str = "") -> list[tuple[str, click.Command]]:
    found: list[tuple[str, click.Command]] = []
    for name in sorted(getattr(command, "commands", {})):
        sub = command.commands[name]  # type: ignore[attr-defined]
        path = f"{prefix} {name}".strip()
        found.append((path, sub))
        if getattr(sub, "commands", None):
            found.extend(_walk(sub, path))
    return found


def command_paths() -> set[str]:
    """Every command path (``keys create``, ``serve``, ...), groups included."""
    return {path for path, _ in _walk(_root())}


def _default(param: click.Parameter) -> str:
    default = getattr(param, "default", None)
    if default is None or default is False or default == () or default == "":
        return ""
    if isinstance(default, bool):
        return "on"
    return f"`{default}`"


def _type_name(param: click.Parameter) -> str:
    if getattr(param, "is_flag", False):
        return "flag"
    kind = param.type
    name = getattr(kind, "name", str(kind)).lower()
    if isinstance(kind, click.Choice):
        return "one of " + ", ".join(f"`{c}`" for c in kind.choices)
    return {"text": "text", "integer": "int", "float": "number", "path": "path"}.get(name, name)


def _first_paragraph(text: str | None) -> str:
    if not text:
        return ""
    return " ".join(inspect.cleandoc(text).split("\n\n")[0].split())


def _options_table(command: click.Command) -> list[str]:
    rows: list[str] = []
    for param in command.params:
        if isinstance(param, click.Argument):
            continue
        flags = ", ".join(f"`{o}`" for o in [*param.opts, *getattr(param, "secondary_opts", [])])
        if param.name == "help":
            continue
        help_text = _first_paragraph(getattr(param, "help", None)).replace("|", "\\|")
        rows.append(f"| {flags} | {_type_name(param)} | {_default(param)} | {help_text} |")
    if not rows:
        return []
    return ["| Option | Type | Default | Meaning |", "| --- | --- | --- | --- |", *rows, ""]


def _arguments(command: click.Command) -> list[str]:
    args = [p for p in command.params if isinstance(p, click.Argument)]
    if not args:
        return []
    lines = ["Arguments:", ""]
    for arg in args:
        required = "required" if arg.required else "optional"
        help_text = _first_paragraph(getattr(arg, "help", None))
        lines.append(f"- `{arg.name}` ({required}){': ' + help_text if help_text else ''}")
    lines.append("")
    return lines


def _usage(path: str, command: click.Command) -> str:
    parts = ["studioforge", path]
    for param in command.params:
        if isinstance(param, click.Argument):
            token = param.name.upper() if param.name else "ARG"
            parts.append(token if param.required else f"[{token}]")
    if any(isinstance(p, click.Option) and p.name != "help" for p in command.params):
        parts.append("[OPTIONS]")
    if getattr(command, "commands", None):
        parts.append("COMMAND [ARGS]...")
    return " ".join(parts)


def render_markdown() -> str:
    """The whole ``docs/CLI.md``."""
    root = _root()
    entries: list[Any] = _walk(root)
    out = [
        "# Command line reference",
        "",
        "<!-- GENERATED by scripts/gen_docs.py from the typer command tree. "
        "Do not edit by hand. -->",
        "",
        "`studioforge` runs the server and manages it. Commands that act on a running server "
        "(`ls`, `ps`, `load`, `unload`, `get`, `update`, `log stream`, `server stop`) talk to it "
        "on this machine over its HTTP API and need no setup: a local admin key is used "
        "automatically. `sfctl` (a separate package) is the same idea for a server on another "
        "machine.",
        "",
        "Every command accepts `--help`. Commands that read configuration take "
        "`--config PATH` (default: the data directory's `config.yaml`; `SF_DATA_DIR` chooses the "
        "data directory).",
        "",
        "| Command | What it does |",
        "| --- | --- |",
    ]
    for path, command in entries:
        summary = _first_paragraph(command.help or getattr(command, "short_help", None))
        out.append(f"| [`studioforge {path}`](#studioforge-{path.replace(' ', '-')}) | {summary} |")
    out.append("")
    for path, command in entries:
        out += [f"## studioforge {path}", "", _first_paragraph(command.help), ""]
        full = inspect.cleandoc(command.help or "")
        extra = full.split("\n\n", 1)[1] if "\n\n" in full else ""
        if extra.strip():
            out += [" ".join(extra.split()), ""]
        out += ["```", _usage(path, command), "```", ""]
        out += _arguments(command)
        out += _options_table(command)
    return "\n".join(out).rstrip("\n") + "\n"
