#: Every catalogued error, keyed by code. Insertion order is the table above;
#: exports sort by code so diffs stay stable.
CATALOG: dict[str, ErrorEntry] = {entry.code: entry for entry in _ENTRIES}

if len(CATALOG) != len(_ENTRIES):  # pragma: no cover - import-time guard
    raise RuntimeError("duplicate error code in error_catalog._ENTRIES")


def lookup(code: str | None) -> ErrorEntry | None:
    """The catalog row for ``code``, or ``None`` for ``None``/unknown codes."""
    if not code:
        return None
    return CATALOG.get(code)


def envelope_extras(code: str | None) -> dict[str, str]:
    """The additive ``fix`` and ``docs`` keys for an error envelope (empty if uncatalogued)."""
    entry = lookup(code)
    if entry is None:
        return {}
    return {"fix": entry.fix, "docs": entry.docs}


def export() -> list[dict[str, Any]]:
    """The catalog as plain data, sorted by code (``docs/contracts/errors.json``)."""
    return [CATALOG[code].to_dict() for code in sorted(CATALOG)]


def render_markdown() -> str:
    """``docs/reference/errors.md``: one anchored section per code (the ``errors/<code>`` slug)."""
    out = [
        "# Error reference",
        "",
        "<!-- GENERATED by scripts/gen_docs.py from studioforge.error_catalog. "
        "Do not edit by hand. -->",
        "",
        f"{len(CATALOG)} error codes. Every API error is an OpenAI-shaped envelope:",
        "",
        "```json",
        '{"error": {"message": "...", "type": "...", "code": "...", "param": null,',
        '           "fix": "what to do about it", "docs": "errors/<code>"}}',
        "```",
        "",
        "`message`, `type`, `code` and `param` are the fields the `openai` clients read. "
        "`fix` and `docs` are additive and present for every catalogued code; `docs` is a "
        "slug that maps onto the section headed by the same code on this page. A `{name}` in "
        "a message is filled in when the error is raised. Codes are stable: they are never "
        "renamed, only added.",
        "",
        "| Code | HTTP | Where |",
        "| --- | --- | --- |",
    ]
    for code in sorted(CATALOG):
        entry = CATALOG[code]
        status = str(entry.http_status) if entry.http_status is not None else "-"
        out.append(f"| [`{code}`](#{code}) | {status} | {entry.surface} |")
    out.append("")
    for code in sorted(CATALOG):
        entry = CATALOG[code]
        status = str(entry.http_status) if entry.http_status is not None else "none"
        out += [
            f"## {code}",
            "",
            f"- HTTP status: {status}",
            f"- Type: `{entry.error_type}`",
            f"- Where: {entry.surface}",
            f"- Docs slug: `{entry.docs}`",
            "",
            f"**Message.** {entry.message}",
            "",
            f"**Fix.** {entry.fix}",
            "",
        ]
    return "\n".join(out).rstrip("\n") + "\n"
