"""The error catalog: one row per stable ``error.code`` the product can emit.

Single source of truth for the P3 standard ("no dead ends"): every code a
caller can see carries an HTTP status, a message template, a suggested fix and
a docs slug. The JSON envelope (:meth:`studioforge.errors.StudioForgeError.
to_payload`) looks the code up here and adds ``fix`` and ``docs`` next to the
four OpenAI keys (additive; ``message``/``type``/``code``/``param`` never move).

``tests/unit/test_error_catalog.py`` scans ``src/`` for every code literal that
can be raised and fails when one is missing from this table, so a new error
cannot ship without a fix and a docs page. Codes are public API: never rename
one, add a new row instead.

``docs`` is a slug (``errors/<code>``), not a URL: ``docs/reference/errors.md``
(generated by ``scripts/gen_docs.py``) has one anchored section per code, and a
published docs site can map the slug onto its own address.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Any

#: Where an error is rendered. ``api`` = the OpenAI-shaped HTTP envelope,
#: ``stream`` = an SSE ``error`` event after the 200 has gone out, ``mcp`` = an
#: MCP tool result, ``watchdog`` = the recovery sidecar, ``panel`` = the control
#: panel's own HTTP surface.
SURFACES = ("api", "stream", "mcp", "watchdog", "panel")


@dataclass(frozen=True)
class ErrorEntry:
    code: str
    #: HTTP status the code is returned with; ``None`` when it never leaves as
    #: an HTTP status of its own (an SSE event or an MCP tool result).
    http_status: int | None
    error_type: str
    #: What the caller is told. ``{name}`` marks a value filled in at raise time.
    message: str
    #: What to do about it. Never empty: an error without a next step is a dead end.
    fix: str
    surface: str = "api"

    @property
    def docs(self) -> str:
        return f"errors/{self.code}"

    def to_dict(self) -> dict[str, Any]:
        row = asdict(self)
        row["docs"] = self.docs
        return row


_INVALID = "invalid_request_error"
_SERVER = "server_error"


def _e(
    code: str,
    status: int | None,
    etype: str,
    message: str,
    fix: str,
    surface: str = "api",
) -> ErrorEntry:
    return ErrorEntry(code, status, etype, message, fix, surface)


